# Plural forms: en (one, other); lv (one, other, zero); ru (one, few, many).
PLURALS: dict[str, dict[str, tuple[str, ...]]] = {
    "rows": {"en": ("row", "rows"), "lv": ("rinda", "rindas", "rindu"),
             "ru": ("строка", "строки", "строк")},
    "variables": {"en": ("variable", "variables"), "lv": ("mainīgais", "mainīgie", "mainīgo"),
                  "ru": ("переменная", "переменные", "переменных")},
    "questions": {"en": ("question", "questions"), "lv": ("jautājums", "jautājumi", "jautājumu"),
                  "ru": ("вопрос", "вопроса", "вопросов")},
    "results": {"en": ("result", "results"), "lv": ("rezultāts", "rezultāti", "rezultātu"),
                "ru": ("результат", "результата", "результатов")},
    "responses": {"en": ("response", "responses"), "lv": ("atbilde", "atbildes", "atbilžu"),
                  "ru": ("ответ", "ответа", "ответов")},
}


def plural_index(language: str, count: int) -> int:
    """gettext plural rules for en, lv and ru."""
    n = abs(int(count))
    if language == "ru":
        if n % 10 == 1 and n % 100 != 11:
            return 0
        if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
            return 1
        return 2
    if language == "lv":
        if n % 10 == 1 and n % 100 != 11:
            return 0
        return 1 if n != 0 else 2
    return 0 if n == 1 else 1


def count_text(language: str, count: int, noun: str) -> str:
    """``5 rows`` / ``5 rindas`` / ``5 строк``."""
    language = language if language in LANGS else "en"
    forms = PLURALS[noun][language]
    return f"{count} {forms[plural_index(language, count)]}"


def t(language: str, key: str, **values) -> str:
    """Translated text; unknown keys fall back to the key itself (visible bug)."""
    row = T.get(key)
    if row is None:
        text = key
    else:
        index = LANGS.index(language) if language in LANGS else 0
        text = row[index] or row[0]
    return text.format(**values) if values else text
