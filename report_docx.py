"""One editable Word document from several results of a project (#42).

Each result in the report contributes, in the researcher's order:
- its heading;
- the dataset line (name, rows, version hash, time);
- the engine's own report text;
- every engine table as a real, editable Word table (APA rules);
- its chart as an embedded PNG figure;
- warnings as a note;
- the researcher's note, labelled as not verified by the engine.

Tables and figures are numbered 1..n in document order, so a reordered
report is renumbered consistently every time it is generated. A running
head and page numbers are in the page header and footer, and an appendix
lists the provenance of every result.

Only saved engine output is used: no number, effect size, interval,
p value or reference is computed, rounded or invented here. A result that
needs review (stale) is refused unless explicitly included; it is then
marked as such in the document.
"""

