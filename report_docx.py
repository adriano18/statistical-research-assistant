@dataclass(frozen=True)
class ReportBlock:
    """What one result contributes to the report."""
    title: str
    report: str
    tables: tuple = ()             # analysis_runs.ResultTable
    figure: bytes | None = None
    section: str = ""
    dataset: str = ""
    rows: int = 0
    dataset_sha256: str = ""
    created: datetime | None = None
    method: str = ""
    run_id: str = ""
    warnings: tuple[str, ...] = ()
    note: str = ""
    stale: tuple[str, ...] = field(default_factory=tuple)


def blocks_from_entries(entries) -> list[ReportBlock]:
    """Report blocks from the workspace's report entries (in report order)."""
    blocks = []
    for entry in entries:
        run = entry.run
        provenance = entry.provenance or {}
        blocks.append(ReportBlock(
            title=run.title, report=run.report or "", tables=tuple(run.tables or ()),
            figure=run.png, section=run.section, dataset=entry.dataset, rows=entry.rows,
            dataset_sha256=str(provenance.get("dataset_sha256") or ""),
            created=entry.created, method=entry.method or run.section,
            run_id=entry.record_id or "", warnings=tuple(run.warnings or ()),
            stale=tuple(entry.stale_reasons or ())))
    return blocks


def _page_field(paragraph) -> None:
    """A PAGE field: Word shows the current page number."""
    run = paragraph.add_run()
    for kind, text in (("begin", None), (None, "PAGE"), ("end", None)):
        if kind:
            element = OxmlElement("w:fldChar")
            element.set(qn("w:fldCharType"), kind)
        else:
            element = OxmlElement("w:instrText")
            element.set(qn("xml:space"), "preserve")
            element.text = text
        run._r.append(element)


def _header_footer(document, running_head: str, labels: dict) -> None:
    section = document.sections[0]
    header = section.header.paragraphs[0]
    header.text = running_head[:60].upper()
    header.alignment = WD_ALIGN_PARAGRAPH.LEFT
    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer.add_run(labels["page"] + " ")
    _page_field(footer)


def _caption(document, label: str, title: str) -> None:
    number = document.add_paragraph()
    number.paragraph_format.keep_with_next = True
    number.add_run(label).bold = True
    heading = document.add_paragraph()
    heading.paragraph_format.keep_with_next = True
    heading.add_run(title).italic = True


def _word_table(document, table) -> None:
    columns = [str(c) for c in table.columns]
    rows = [[str(v) for v in row] for row in table.rows]
    if not columns or len(columns) * (len(rows) + 1) > MAX_TABLE_CELLS:
        raise ValueError(f"Table “{table.title}” is too large for a report.")
    word = document.add_table(rows=1, cols=len(columns))
    word.alignment = WD_TABLE_ALIGNMENT.CENTER
    for cell, label in zip(word.rows[0].cells, columns):
        cell.text = label
        for paragraph in cell.paragraphs:
            paragraph.paragraph_format.line_spacing = 1
            for run in paragraph.runs:
                run.bold = True
    # The header row repeats on every page of a long table.
    header_properties = word.rows[0]._tr.get_or_add_trPr()
    repeat = OxmlElement("w:tblHeader")
    repeat.set(qn("w:val"), "true")
    header_properties.append(repeat)
    for values in rows:
        cells = word.add_row().cells
        for cell, value in zip(cells, values + [""] * (len(columns) - len(values))):
            cell.text = value
            for paragraph in cell.paragraphs:
                paragraph.paragraph_format.line_spacing = 1
    _table_borders(word)


def _paragraphs(document, text: str) -> None:
    for chunk in re.split(r"\n\s*\n", text.strip()):
        if chunk.strip():
            paragraph = document.add_paragraph()
            lines = chunk.strip().splitlines()
            for index, line in enumerate(lines):
                run = paragraph.add_run(line.rstrip())
                if index < len(lines) - 1:
                    run.add_break(WD_BREAK.LINE)


def build_report_docx(blocks: list[ReportBlock], *, title: str = "", language: str = "en",
                      project: str = "", version: str = "", allow_stale: bool = False,
                      generated: datetime | None = None) -> Document:
    """The combined report as a python-docx Document; raises ValueError."""
    labels = LABELS.get(language, LABELS["en"])
    if not blocks:
        raise ValueError("The report has no results.")
    if len(blocks) > MAX_BLOCKS:
        raise ValueError(f"A report holds at most {MAX_BLOCKS} results.")
    stale = [b.title for b in blocks if b.stale]
    if stale and not allow_stale:
        raise ValueError("These results need review: " + "; ".join(stale)
                         + ". Recalculate them, remove them, or include them marked as needing review.")
    title = (title or "").strip()[:250] or labels["default_title"]
    when = generated or datetime.now()
    document = Document()
    _style(document)
    document.core_properties.title = title
    document.core_properties.subject = "Research report (editable draft)"
    document.core_properties.keywords = "statistics; research report; editable"
    document.core_properties.author = ""
    _header_footer(document, title, labels)

    heading = document.add_paragraph(style="Title")
    heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
    heading.add_run(title)
    if project and project != title:
        sub = document.add_paragraph(project)
        sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    note = document.add_paragraph(labels["generated"].format(
        version=version or "", date=when.strftime("%Y-%m-%d"), project=project or title))
    note.runs[0].italic = True
    document.add_heading(labels["contents"], level=1)
    for number, block in enumerate(blocks, start=1):
        marker = f" ({labels['needs_review']})" if block.stale else ""
        document.add_paragraph(f"{number}. {block.title}{marker}")

    table_number = figure_number = 0
    for number, block in enumerate(blocks, start=1):
        document.add_page_break()
        marker = f" — {labels['needs_review']}" if block.stale else ""
        document.add_heading(f"{number}. {block.title}{marker}", level=1)
        line = document.add_paragraph()
        line.add_run(labels["dataset"].format(
            name=block.dataset or "-", rows=block.rows, sha=(block.dataset_sha256 or "-")[:12],
            when=block.created.strftime("%Y-%m-%d %H:%M") if block.created else "-")).italic = True
        if block.stale:
            warning = document.add_paragraph()
            warning.add_run(labels["stale_note"].format(reasons="; ".join(block.stale))).bold = True
        _paragraphs(document, block.report)
        for table in block.tables:
            table_number += 1
            _caption(document, f"{labels['table']} {table_number}", str(table.title or block.title))
            _word_table(document, table)
        if block.figure:
            figure_number += 1
            _caption(document, f"{labels['figure']} {figure_number}",
                     f"{labels['figure_title']}: {block.title}")
            document.add_picture(_figure_body(block.figure, block.section), width=Inches(6.0))
        if block.warnings:
            paragraph = document.add_paragraph()
            paragraph.add_run(labels["note"]).italic = True
            paragraph.add_run(" " + labels["warnings"] + " " + " ".join(block.warnings))
        if block.note.strip():
            paragraph = document.add_paragraph()
            paragraph.add_run(labels["researcher_note"]).italic = True
            paragraph.add_run(" " + block.note.strip())

    document.add_page_break()
    document.add_heading(labels["provenance"], level=1)
    document.add_paragraph(labels["provenance_note"])
    provenance = document.add_table(rows=1, cols=len(labels["columns"]))
    provenance.alignment = WD_TABLE_ALIGNMENT.CENTER
    for cell, label in zip(provenance.rows[0].cells, labels["columns"]):
        cell.text = label
    for number, block in enumerate(blocks, start=1):
        cells = provenance.add_row().cells
        values = (str(number), block.title, block.method, block.dataset,
                  (block.dataset_sha256 or "-")[:12], str(block.rows),
                  block.created.strftime("%Y-%m-%d %H:%M") if block.created else "-",
                  (block.run_id or "-")[:12])
        for cell, value in zip(cells, values):
            cell.text = value
            for paragraph in cell.paragraphs:
                paragraph.paragraph_format.line_spacing = 1
                for run in paragraph.runs:
                    run.font.size = Pt(9)
    _table_borders(provenance)
    return document


def default_file_name(title: str, when: datetime | None = None) -> str:
    """A new name for every export, so a report edited in Word is never
    replaced by the next export unless the researcher chooses that file."""
    stem = re.sub(r"[^\w\- ]+", "", (title or "research report"), flags=re.UNICODE).strip()
    stem = re.sub(r"\s+", "_", stem)[:60] or "research_report"
    return f"{stem}_{(when or datetime.now()):%Y-%m-%d_%H%M}.docx"


def save_report_docx(path: Path, document: Document) -> Path:
    """Write atomically (a half-written file never replaces an existing one)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp = tempfile.mkstemp(prefix=".report-", suffix=".docx", dir=path.parent)
    os.close(fd)
    try:
        document.save(temp)
        os.replace(temp, path)
    except BaseException:
        Path(temp).unlink(missing_ok=True)
        raise
    return path
