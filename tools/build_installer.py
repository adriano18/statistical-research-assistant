"""Build the Windows installer from a ``flet build windows`` folder (#44).

    python tools/build_installer.py build/windows --out dist
    python tools/build_installer.py build/windows --out dist --layout-only   # any OS

Reads the version and channel from the bundle's ``app/build_info.json``,
writes ``packaging/windows/generated-layout.iss`` (the program's own
top-level files and folders, so an update first removes the previous
version's copies and the uninstaller removes what the program created in
them), runs Inno Setup's ISCC and writes ``<installer>.sha256`` and
``installer.json`` (name, version, channel, size, SHA-256, AppId).

Signing: pass ``--sign-command`` with a signtool command line that contains
``$f`` (Inno Setup's SignTool syntax); setup and uninstaller are then
signed. Without it the installer is an unsigned preview and says so in
``installer.json``.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import app_identity  # noqa: E402

SCRIPT = ROOT / "packaging" / "windows" / "StatisticalResearchAssistant.iss"
LAYOUT = SCRIPT.parent / "generated-layout.iss"
EXE = "StatisticalResearchAssistant.exe"
# Inside the program's "app" folder: questionnaires of very old portable
# previews may live in app\data; the installer never deletes it.
KEEP_IN_APP = {"data"}


def find_bundle(folder: Path) -> Path:
    folder = Path(folder)
    if (folder / EXE).is_file():
        return folder
    for path in sorted(folder.rglob(EXE)):
        return path.parent
    raise SystemExit(f"No {EXE} under {folder}")


def _iss_name(path: str) -> str:
    if any(ch in path for ch in '"\r\n'):
        raise SystemExit(f"Unexpected file name in the bundle: {path!r}")
    return path


def layout(bundle: Path) -> str:
    """[InstallDelete] and [UninstallDelete] entries for the bundle's own items."""
    entries = []
    for item in sorted(bundle.iterdir(), key=lambda p: p.name.lower()):
        if item.name == "app" and item.is_dir():
            for inner in sorted(item.iterdir(), key=lambda p: p.name.lower()):
                if inner.name in KEEP_IN_APP:
                    continue
                entries.append(("app\\" + inner.name, inner.is_dir()))
            entries.append(("app\\__pycache__", True))
        else:
            entries.append((item.name, item.is_dir()))
    lines = ["; Generated by tools/build_installer.py; do not edit.", "[InstallDelete]"]
    for name, is_dir in entries:
        kind = "filesandordirs" if is_dir else "files"
        lines.append(f'Type: {kind}; Name: "{{app}}\\{_iss_name(name)}"')
    lines.append("")
    lines.append("[UninstallDelete]")
    for name, is_dir in entries:
        if is_dir:
            lines.append(f'Type: filesandordirs; Name: "{{app}}\\{_iss_name(name)}"')
    return "\n".join(lines) + "\n"


def read_info(bundle: Path) -> app_identity.BuildInfo:
    path = bundle / "app" / app_identity.BUILD_INFO
    if not path.is_file():
        raise SystemExit(f"{path} is missing: run tools/write_build_info.py before flet build")
    return app_identity.read_build_info(path)


def iscc() -> str:
    found = shutil.which("ISCC") or shutil.which("iscc")
    if found:
        return found
    for base in (os.environ.get("ProgramFiles(x86)"), os.environ.get("ProgramFiles"),
                 os.path.join(os.environ.get("LOCALAPPDATA", ""), "Programs")):
        if base and Path(base, "Inno Setup 6", "ISCC.exe").is_file():
            return str(Path(base, "Inno Setup 6", "ISCC.exe"))
    raise SystemExit("Inno Setup 6 (ISCC.exe) was not found.")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("bundle", type=Path)
    parser.add_argument("--out", type=Path, default=ROOT / "dist")
    parser.add_argument("--compression", default="lzma2/max")
    parser.add_argument("--publisher", default="Statistical Research Assistant")
    parser.add_argument("--sign-command", default="",
                        help="signtool command line with $f, e.g. signtool sign /fd sha256 ... $f")
    parser.add_argument("--layout-only", action="store_true")
    args = parser.parse_args(argv)

    bundle = find_bundle(args.bundle)
    info = read_info(bundle)
    version = info.parsed_version
    LAYOUT.write_text(layout(bundle), encoding="utf-8")
    if args.layout_only:
        print(LAYOUT.read_text(encoding="utf-8"))
        return 0
    args.out.mkdir(parents=True, exist_ok=True)
    command = [iscc(), "/Qp", f"/DAppVersion={version}", f"/DNumericVersion={version.numeric}",
               f"/DSourceDir={bundle.resolve()}", f"/DOutputDir={args.out.resolve()}",
               f"/DCompression={args.compression}", f"/DPublisher={args.publisher}"]
    if args.sign_command:
        command += [f"/Ssratool={args.sign_command}", "/DSignTool=sratool"]
    command.append(str(SCRIPT))
    subprocess.run(command, check=True)
    installer = args.out / f"StatisticalResearchAssistant-{version}-Setup.exe"
    if not installer.is_file():
        raise SystemExit(f"ISCC did not write {installer}")
    digest = sha256(installer)
    (args.out / (installer.name + ".sha256")).write_text(f"{digest}  {installer.name}\n",
                                                          encoding="utf-8")
    meta = {
        "file": installer.name, "version": str(version), "channel": info.channel,
        "build": info.build, "commit": info.commit, "size": installer.stat().st_size,
        "sha256": digest, "app_id": app_identity.INSTALLER_APP_ID,
        "signed": bool(args.sign_command), "compression": args.compression,
    }
    (args.out / "installer.json").write_text(json.dumps(meta, indent=1) + "\n", encoding="utf-8")
    print(json.dumps(meta))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
