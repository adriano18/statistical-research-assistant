"""Stage 37 (Issue #66): the H1–H6 synthetic master's acceptance scenario.

Everything here is SYNTHETIC. The fixture is generated by the owner's
``tests/fixtures/stage37/generate_master_fixture.py`` (v1, unchanged), the
constructs are scored from its spec JSON and from the public mapping
``tests/fixtures/stage37/synthetic_construct_mapping.json``, and no output is
an empirical finding. docs/STAGE37_MASTER_ACCEPTANCE.md describes the
scenario.

The scenario is run as a researcher would run it, headless: a project, a
typed plan with H1–H8 (H7 and H8 exploratory: Models 7 and 14 as separate,
explicitly specified analyses), tasks linked to hypotheses with the 37.0a
API (``hypothesis_id`` and the hypothesis snapshot of the run), every
analysis through ``workspace_methods.run_method`` with the researcher's
confirmations, supporting analyses (reliability and item diagnostics,
descriptives, the prorated-score sensitivity re-runs), and a Word report.

Review S6: the fixture has only DIM1 tied to Y, no negative coping
dimension, no reverse-keyed items and covariates without effects, so the
tests assert numbers against independent oracles and never significance.
The reviewer's reference values (review S3, S5, §4) are checked as a
secondary cross-check.

Set ``SRA_ACCEPTANCE_OUT`` to a folder to keep the Word report and the
summary text of a run.
"""

