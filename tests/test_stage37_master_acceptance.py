def items(spec: dict | list) -> list[str]:
    parts = spec if isinstance(spec, list) else [spec]
    return [f"{p['prefix']}{j:02d}" for p in parts for j in range(p["first"], p["last"] + 1)]


def question_ids():
    return {"predict": "a1b2c3d4e5f6", "relate": "b2c3d4e5f6a1", "process": "c3d4e5f6a1b2"}


class Scenario:
    """One complete run of the acceptance scenario in ``folder``."""

    def __init__(self, folder: Path):
        from project_store import ProjectStore
        from workspace_state import ResearchSession

        self.folder = folder
        self.mapping = json.loads(MAPPING.read_text(encoding="utf-8"))
        self.csv, spec_path = fixture.generate(folder / "fixture")
        self.spec = json.loads(spec_path.read_text(encoding="utf-8"))
        raw = pd.read_csv(self.csv)
        self.raw = raw.copy()
        names = {key: self.spec[key].split()[0] for key in ("X", "M", "W", "Y")}
        self.X, self.M, self.W, self.Y = (names[k] for k in ("X", "M", "W", "Y"))
        constructs = self.mapping["constructs"]
        self.items = {key: items(constructs[key]["items"]) for key in constructs}
        dims = self.mapping["coping_dimensions"]
        self.AVOID = dims["avoidance_like"]["column"]
        self.ASSERT = dims["assertive_like"]["column"]
        self.items["avoidance_like"] = items(dims["avoidance_like"]["items"])
        self.items["assertive_like"] = items(dims["assertive_like"]["items"])
        # Scoring from the mapping: means of complete answers (listwise per
        # scale), prorated means (answered items) for the sensitivity runs,
        # 0/1 codes of sex for the path models.
        frame = raw.copy()
        frame[self.AVOID] = frame[self.items["avoidance_like"]].mean(axis=1, skipna=False)
        frame[self.ASSERT] = frame[self.items["assertive_like"]].mean(axis=1, skipna=False)
        frame["SYN_COPE_DIM1_PRORATED"] = frame[self.items["M"]].mean(axis=1)
        frame["SYN_SUP_PRORATED"] = frame[self.items["W"]].mean(axis=1)
        frame["SYN_SEX_1"] = (frame["sex_code"] == 1).astype(float)
        frame["SYN_SEX_2"] = (frame["sex_code"] == 2).astype(float)
        self.frame = frame
        self.covariates = ["age_years", "SYN_SEX_1", "SYN_SEX_2", "employed_code"]
        levels = {"participant_code": "id"}
        for column in frame.columns:
            if column.startswith(("SYN_LON_", "SYN_SUP_", "SYN_WELL_", "SYN_COPE_")) \
                    and column[-2:].isdigit():
                levels[column] = "ordinal"
        for column in (self.X, self.M, self.W, self.Y, self.AVOID, self.ASSERT,
                       "SYN_COPE_DIM1_PRORATED", "SYN_SUP_PRORATED", "age_years"):
            levels[column] = "scale"
        for column in ("sex_code", "employed_code", "SYN_SEX_1", "SYN_SEX_2"):
            levels[column] = "nominal"
        self.levels = levels
        self.session = ResearchSession()
        self.session.set_dataset(frame, "synthetic_master_research_n180.csv")
        for name, level in levels.items():
            self.session.confirm_level(name, level)
        self.store = ProjectStore(folder / "projects")
        self.info = self.store.create("SYNTHETIC — Stage 37 master's acceptance (invented data)",
                                      description=self.mapping["notice"])
        self.runs: dict[str, object] = {}
        self.linked: dict[str, str | None] = {}
        self.records: dict[str, object] = {}
        self.entries: dict[str, object] = {}
        self.tasks: dict[str, object] = {}
        with self.store.open(self.info.id) as project:
            self.project = project
            self.dataset = project.import_table(frame, "synthetic_master_research_n180.csv")
            project.save_levels(self.dataset.id, {n: (lvl, "acceptance")
                                                  for n, lvl in levels.items()})
            project.add_question(QUESTION)
            self.plan_version = project.save_plan(self.plan())
            self.plan_entry = project.plan()
            self.status = project.hypothesis_status()
            self.hypotheses = {f"H{i}": h["id"] for i, h in
                               enumerate(self.plan_entry["plan"]["hypotheses"], start=1)}
            self.analyse()
            self.protocol = project.protocol_records()
            self.stored = {key: project.run(record.id) for key, record in self.records.items()}
        self.report()

    # -------------------------------------------------------------- plan
    def plan(self) -> dict:
        ids = question_ids()
        hypotheses = []
        roles = {
            "H1": ("predict", "linear_model", {}, {"outcome": self.Y,
                                                   "predictors": [self.X, "age_years",
                                                                  "sex_code", "employed_code"]}),
            "H2": ("relate", "batch_correlation", {"method": "pearson"},
                   {"x": self.X, "y": [self.AVOID, self.ASSERT]}),
            "H3": ("relate", "batch_correlation", {"method": "pearson"},
                   {"x": self.Y, "y": [self.M, self.AVOID, self.ASSERT]}),
            "H4": ("process", "mediation", {}, {"x": self.X, "y": self.Y,
                                                "mediators": [self.M, self.AVOID],
                                                "covariates": self.covariates}),
            "H5": ("process", "moderation", {}, {"x": self.X, "y": self.Y, "w": self.W,
                                                 "covariates": self.covariates}),
            "H6": ("process", "moderation", {}, {"x": self.X, "y": self.AVOID, "w": self.W,
                                                 "covariates": self.covariates}),
            "H7": ("process", "conditional_process", {"method": "7"},
                   {"x": self.X, "y": self.Y, "mediators": [self.M], "w": self.W,
                    "covariates": self.covariates}),
            "H8": ("process", "conditional_process", {"method": "14"},
                   {"x": self.X, "y": self.Y, "mediators": [self.M], "w": self.W,
                    "covariates": self.covariates}),
        }
        for key, (kind, method, options, planned) in roles.items():
            definition = self.mapping["hypotheses"][key]
            hypotheses.append({
                "text": definition["text"], "h0": "[SYNTHETIC] The population value is zero.",
                "priority": definition.get("priority", "primary"), "direction": "two-sided",
                "alpha": 0.05, "question_id": ids[kind], "method_key": method,
                **({"method_options": options} if options else {}), "roles": planned})
        return {"objectives": "[SYNTHETIC] How are the invented X-, M-, W- and Y-like scores of "
                            "the Stage 37 fixture related? (Not an empirical study.)",
                "questions": [{"id": ids[k], "type": k,
                               "text": f"[SYNTHETIC] {k} question of the acceptance scenario"}
                              for k in ("predict", "relate", "process")],
                "hypotheses": hypotheses}

    # -------------------------------------------------------------- analyses
    def run(self, name: str, key: str, roles: dict, *, hypothesis: str | None = None,
            goal: str = "", **options):
        from research_workflow import hypothesis_snapshot
        from workspace_methods import METHODS, default_options, required_confirmations, run_method

        spec = METHODS[key]
        chosen = {**default_options(spec), **options}
        needed = list(required_confirmations(spec, chosen))
        if key in ("item_diagnostics",):
            from workspace_methods import ITEMS_NOT_TOTALS

            needed = [c for c in needed if c.key != ITEMS_NOT_TOTALS.key]
        confirms = {c.key: True for c in needed}
        run = run_method(key, self.session, roles, chosen, confirms)
        hid = self.hypotheses.get(hypothesis) if hypothesis else None
        task = self.project.save_task(task_id=None, title=f"{hypothesis or 'Support'}: {name}",
                                      goal=goal, selection=roles, method=key, options=chosen,
                                      confirms=confirms, hypothesis_id=hid)
        snapshot = hypothesis_snapshot(self.plan_entry, self.status, hid) if hid else None
        labels = [c.label for c in needed]
        used = {n for value in roles.values() for n in (value if isinstance(value, list)
                                                        else [value]) if n}
        record = self.project.record_run(
            run, method=key, dataset_id=self.dataset.id, roles=roles, options=chosen,
            confirms=confirms, confirmations=labels,
            levels={n: self.levels[n] for n in sorted(used)}, task_id=task.id,
            hypothesis=snapshot)
        self.project.set_note(record.id, SYNTHETIC_NOTE)
        if hid:
            self.project.add_protocol_record("link", hypothesis_id=hid, task_id=task.id,
                                             run_id=record.id)
        entry = self.session.add_result(run, labels, method=key, roles=roles, options=chosen,
                                        confirms=confirms, task_id=task.id, hypothesis=snapshot,
                                        record_id=record.id)
        entry.note = SYNTHETIC_NOTE
        self.runs[name], self.records[name], self.entries[name] = run, record, entry
        self.linked[name] = hypothesis
        self.tasks[name] = task
        return run

    def analyse(self) -> None:
        X, M, W, Y, AVOID, ASSERT = self.X, self.M, self.W, self.Y, self.AVOID, self.ASSERT
        # Supporting analyses: reliability and item diagnostics, descriptives.
        for key, label in (("X", X), ("M", M), ("W", W), ("Y", Y),
                           ("avoidance_like", AVOID), ("assertive_like", ASSERT)):
            self.run(f"scale {key}", "item_diagnostics", {"items": self.items[key]},
                     goal="scale", ci="0")
            self.run(f"describe {key}", "descriptive", {"variable": label}, goal="describe")
        # H1: correlation, and the linear model with categorical covariates.
        self.run("H1 correlation", "correlation", {"x": X, "y": Y}, hypothesis="H1",
                 goal="relate", method="pearson")
        self.run("H1 linear model", "linear_model",
                 {"outcome": Y, "predictors": [X, "age_years"],
                  "factors": ["sex_code", "employed_code"]}, hypothesis="H1", goal="predict")
        # H2, H3: batch correlations with Holm.
        self.run("H2", "batch_correlation", {"x": X, "ys": [AVOID, ASSERT]}, hypothesis="H2",
                 goal="relate", method="pearson", adjust="holm")
        self.run("H3", "batch_correlation", {"x": Y, "ys": [M, AVOID, ASSERT]},
                 hypothesis="H3", goal="relate", method="pearson", adjust="holm")
        # H4: parallel mediation with covariates (Model 4).
        h4 = {"x": X, "mediators": [M, AVOID], "y": Y, "covariates": self.covariates}
        self.run("H4", "mediation", h4, hypothesis="H4", goal="process")
        # H5, H6: moderation (Model 1).
        self.run("H5", "moderation", {"x": X, "w": W, "y": Y, "covariates": self.covariates},
                 hypothesis="H5", goal="process")
        self.run("H6", "moderation",
                 {"x": X, "w": W, "y": AVOID, "covariates": self.covariates},
                 hypothesis="H6", goal="process")
        # Models 7 and 14: separate, explicitly specified analyses (exploratory).
        process = {"x": X, "mediators": [M], "w": W, "y": Y, "covariates": self.covariates}
        self.run("H7 model 7", "conditional_process", process, hypothesis="H7",
                 goal="process", method="7", sensitivity="500")
        self.run("H8 model 14", "conditional_process", process, hypothesis="H8",
                 goal="process", method="14")
        # Missing-data sensitivity: prorated scores keep the cases with a missing item.
        self.run("H4 prorated", "mediation",
                 {**h4, "mediators": ["SYN_COPE_DIM1_PRORATED", AVOID]}, goal="process")
        self.run("H5 prorated", "moderation",
                 {"x": X, "w": "SYN_SUP_PRORATED", "y": Y, "covariates": self.covariates},
                 goal="process")

    # -------------------------------------------------------------- report
    def report(self) -> None:
        import research_report as rr
        from report_docx import build_research_docx, save_report_docx

        plan = self.plan_entry["plan"]
        hypotheses = [{"text": h["text"], "h0": h.get("h0", ""), "priority": h["priority"],
                       "standing": self.status[h["id"]]["standing"]} for h in plan["hypotheses"]]
        infos = [rr.result_info(entry, task_title=self.tasks[name].title, note=SYNTHETIC_NOTE)
                 for name, entry in self.entries.items()]
        self.report_plan = rr.plan_report(rr.ReportInputs(
            title=self.info.title, project=self.info.title, question=QUESTION,
            hypotheses=hypotheses, results=infos))
        self.docx_path = save_report_docx(self.folder / "stage37_acceptance_report.docx",
                                          build_research_docx(self.report_plan))

    def normalised_report(self) -> list:
        """The report plan without calculation times (for reproducibility)."""
        out = []
        for section in self.report_plan.sections:
            for item in section.items:
                if item.kind == "note" and item.text.startswith("Data:"):
                    continue
                rows = item.rows
                if section.key == "appendix" and item.kind == "table":
                    rows = tuple(row[:-1] for row in rows)      # without the run's uuid
                out.append((section.key, item.kind, item.text, item.title, item.columns,
                            rows))
        return out


class MasterAcceptanceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp = tempfile.TemporaryDirectory()
        cls.s = Scenario(Path(cls.temp.name) / "first")
        out = os.environ.get("SRA_ACCEPTANCE_OUT")
        if out:
            target = Path(out)
            target.mkdir(parents=True, exist_ok=True)
            shutil.copy2(cls.s.docx_path, target / cls.s.docx_path.name)
            summary = [f"{name}\n{run.summary}\n" for name, run in cls.s.runs.items()]
            (target / "stage37_acceptance_summary.txt").write_text(
                SYNTHETIC_NOTE + "\n\n" + "\n".join(summary), encoding="utf-8")

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()

    def assertClose(self, actual, expected, rel=EXACT, abs_tol=1e-12, msg=""):
        self.assertTrue(math.isclose(float(actual), float(expected), rel_tol=rel,
                                     abs_tol=abs_tol), f"{msg}: {actual!r} != {expected!r}")

    def complete(self, columns) -> pd.DataFrame:
        return self.s.frame[list(columns)].dropna()

    # ---------------------------------------------------------- data and scores
    def test_fixture_mapping_and_scores(self):
        s = self.s
        self.assertEqual(s.raw.shape, (180, 98))
        self.assertTrue(s.raw["participant_code"].is_unique)
        for column, rows in s.spec["missing"].items():
            missing = [i + 1 for i in np.flatnonzero(s.raw[column].isna())]
            self.assertEqual(missing, rows, column)
        self.assertEqual(s.mapping["constructs"]["X"]["column"], s.X)
        self.assertEqual(s.mapping["constructs"]["Y"]["column"], s.Y)
        # The generator's coping groups: 4 groups of 7 items, then 4 of 6.
        sizes = [7, 7, 7, 7, 6, 6, 6, 6]
        starts = np.cumsum([0, *sizes])
        group = {g: [f"SYN_COPE_{j:02d}" for j in range(starts[g] + 1, starts[g + 1] + 1)]
                 for g in range(8)}
        self.assertEqual(s.items["avoidance_like"], group[2] + group[5])
        self.assertEqual(s.items["assertive_like"], group[3] + group[6])
        self.assertEqual(s.items["M"], group[0])
        values = s.raw[s.items["avoidance_like"]].to_numpy(float)
        np.testing.assert_allclose(s.frame[s.AVOID], values.mean(axis=1), rtol=0, atol=1e-12)
        # The fixture's own scores agree with the items (sum, mean, sum × 4).
        np.testing.assert_array_equal(s.raw[s.X], s.raw[s.items["X"]].sum(axis=1))
        np.testing.assert_allclose(s.raw[s.Y], 4 * s.raw[s.items["Y"]].sum(axis=1))
        dim1 = s.raw[s.items["M"]].mean(axis=1, skipna=False).round(6)
        pd.testing.assert_series_equal(s.raw[s.M], dim1, check_names=False)

    def test_reliability_item_diagnostics_and_descriptives(self):
        s = self.s
        expected_alpha = {"X": 0.914, "W": 0.903, "Y": 0.812, "M": 0.802}   # reviewer, 3 dp
        for key in ("X", "M", "W", "Y", "avoidance_like", "assertive_like"):
            result = s.runs[f"scale {key}"].result
            values = s.raw[s.items[key]].dropna().to_numpy(float)
            k = values.shape[1]
            alpha = k / (k - 1) * (1 - values.var(axis=0, ddof=1).sum()
                                   / values.sum(axis=1).var(ddof=1))
            self.assertClose(result.alpha.value, alpha, msg=f"alpha {key}")
            if key in expected_alpha:
                self.assertAlmostEqual(result.alpha.value, expected_alpha[key], places=3)
            if k > 12:     # S13: ω is validated for 3–12 items only
                self.assertEqual(result.omega.status, "not_calculated", key)
            describe = s.runs[f"describe {key}"].result
            column = {"X": s.X, "M": s.M, "W": s.W, "Y": s.Y, "avoidance_like": s.AVOID,
                      "assertive_like": s.ASSERT}[key]
            self.assertClose(describe.quantity("mean").value, s.frame[column].mean(), msg="M")
            self.assertClose(describe.quantity("sd").value, s.frame[column].std(ddof=1),
                             msg="SD")

    # ---------------------------------------------------------- hypotheses
    def test_h1_correlation_and_linear_model_with_categorical_covariates(self):
        s = self.s
        data = self.complete([s.X, s.Y])
        self.assertClose(s.runs["H1 correlation"].result.coefficient,
                         np.corrcoef(data[s.X], data[s.Y])[0, 1], msg="r")
        result = s.runs["H1 linear model"].result
        rows = self.complete([s.Y, s.X, "age_years", "sex_code", "employed_code"])
        fit = smf.ols(f"{s.Y} ~ {s.X} + age_years + C(sex_code) + C(employed_code)",
                      data=rows).fit()
        self.assertEqual(result.n, len(rows))
        self.assertClose(result.r_squared, fit.rsquared, msg="R²")
        self.assertClose(result.coefficient(f"x:{s.X}").b, fit.params[s.X], msg="b_X")
        self.assertClose(result.coefficient("d:sex_code=2").b, fit.params["C(sex_code)[T.2]"],
                         msg="sex = 2")
        self.assertEqual(result.references, {"sex_code": "0", "employed_code": "0"})
        matrix = result.design.to_numpy()
        for j, c in enumerate(result.coefficients[1:], start=1):
            self.assertClose(c.vif, variance_inflation_factor(matrix, j), rel=1e-8, msg=c.term)

    def test_h2_and_h3_batch_correlations_with_holm(self):
        s = self.s
        for name, focal, others in (("H2", s.X, [s.AVOID, s.ASSERT]),
                                    ("H3", s.Y, [s.M, s.AVOID, s.ASSERT])):
            family = s.runs[name].result
            self.assertEqual(family.adjustment, "holm")
            for row, other in zip(family.rows, others):
                pair = self.complete([focal, other])
                self.assertEqual(row.n, len(pair))
                self.assertClose(row.estimate, np.corrcoef(pair[focal], pair[other])[0, 1],
                                 msg=f"{name} r {other}")
            expected = multipletests([row.p_raw for row in family.rows], method="holm")[1]
            np.testing.assert_allclose([row.p_adjusted for row in family.rows], expected,
                                       rtol=1e-12)

    def test_h4_parallel_mediation_with_covariates_and_bootstrap(self):
        s = self.s
        run = s.runs["H4"]
        result = run.result
        covs = " + ".join(s.covariates)
        rows = self.complete([s.X, s.M, s.AVOID, s.Y, *s.covariates])
        self.assertEqual(result.n, len(rows))
        a1 = smf.ols(f"{s.M} ~ {s.X} + {covs}", data=rows).fit().params[s.X]
        a2 = smf.ols(f"{s.AVOID} ~ {s.X} + {covs}", data=rows).fit().params[s.X]
        y = smf.ols(f"{s.Y} ~ {s.X} + {s.M} + {s.AVOID} + {covs}", data=rows).fit()
        total = smf.ols(f"{s.Y} ~ {s.X} + {covs}", data=rows).fit().params[s.X]
        self.assertClose(result.estimate("a:m0").value, a1, msg="a1")
        self.assertClose(result.estimate("a:m1").value, a2, msg="a2")
        self.assertClose(result.estimate("b:m0").value, y.params[s.M], msg="b1")
        self.assertClose(result.estimate("direct").value, y.params[s.X], msg="c'")
        self.assertClose(result.estimate("total").value, total, msg="c")
        self.assertClose(result.estimate("indirect:m0").value, a1 * y.params[s.M], msg="a1b1")
        self.assertClose(total, y.params[s.X] + a1 * y.params[s.M] + a2 * y.params[s.AVOID],
                         rel=1e-10, msg="c = c′ + Σab")
        self.assertEqual((run.inputs["resamples"], run.inputs["seed"]), (5000, 37066))
        self.assertEqual(run.inputs["valid_resamples"], 5000)
        stored = s.stored["H4"]
        self.assertEqual(stored.provenance["inputs"]["bootstrap_indices_sha256"],
                         result.bootstrap.indices_sha256)
        # Review S5 on this model: ab > 0 while c′ and c < 0.
        if result.estimate("indirect:m0").value > 0 > result.estimate("total").value:
            self.assertIn("inconsistent mediation (suppression", run.interpretation)
        self.assertNotIn("partial mediation", run.report.lower())

    def test_h5_and_h6_moderation_with_simple_slopes(self):
        s = self.s
        covs = " + ".join(s.covariates)
        for name, outcome in (("H5", s.Y), ("H6", s.AVOID)):
            result = s.runs[name].result
            rows = self.complete([s.X, s.W, outcome, *s.covariates])
            fit = smf.ols(f"{outcome} ~ {s.X} * {s.W} + {covs}", data=rows).fit()
            self.assertClose(result.estimate("interaction").value,
                             fit.params[f"{s.X}:{s.W}"], msg=f"{name} b3")
            names = list(fit.params.index)
            for estimate in result.conditional:
                contrast = np.zeros(len(names))
                contrast[names.index(s.X)] = 1.0
                contrast[names.index(f"{s.X}:{s.W}")] = estimate.w
                test = fit.t_test(contrast)
                self.assertClose(estimate.value, float(np.squeeze(test.effect)), msg="slope")
                self.assertClose(estimate.se, float(np.squeeze(test.sd)), msg="slope SE")
            for point in result.johnson_neyman.points:
                contrast = np.zeros(len(names))
                contrast[names.index(s.X)] = 1.0
                contrast[names.index(f"{s.X}:{s.W}")] = point
                self.assertAlmostEqual(float(np.squeeze(fit.t_test(contrast).pvalue)), 0.05,
                                       places=8)

